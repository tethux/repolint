func TestFixPermissionsAndStructuralOptIn(t *testing.T) {
	root := newFixtureModule(t)
	source := writeFixture(t, root, "bridge/value.go", "package bridge; import \"errors\"; func f() error {return errors.New(\"broken\")}")
	before := readFixture(t, source)
	if fixErr := lintRoot(root, options{fix: true}, func(d diagnostic) {}); fixErr != nil {
		t.Fatal(fixErr)
	}
	if readFixture(t, source) != before {
		t.Fatal("safe fix made structural edits")
	}
	if fixErr := lintRoot(root, options{fix: true, diff: true, allowStructural: true}, func(d diagnostic) {}); fixErr != nil {
		t.Fatal(fixErr)
	}
	if readFixture(t, source) != before {
		t.Fatal("diff wrote source")
	}
	if _, statErr := os.Stat(filepath.Join(root, "bridge/errs")); !os.IsNotExist(statErr) {
		t.Fatal("diff created error domain")
	}
	if chmodErr := os.Chmod(source, 0o640); chmodErr != nil {
		t.Fatal(chmodErr)
	}
	if fixErr := lintRoot(root, options{fix: true, allowStructural: true}, func(d diagnostic) { t.Errorf("remaining diagnostic: %+v", d) }); fixErr != nil {
		t.Fatal(fixErr)
	}
	info, statErr := os.Stat(source)
	if statErr != nil {
		t.Fatal(statErr)
	}
	if info.Mode().Perm() != 0o640 {
		t.Fatal("fix changed permissions")
	}
	fixed := readFixture(t, source)
	if fixErr := lintRoot(root, options{fix: true, allowStructural: true}, func(d diagnostic) {}); fixErr != nil {
		t.Fatal(fixErr)
	}
	if readFixture(t, source) != fixed {
		t.Fatal("second fix changed source")
	}
}

