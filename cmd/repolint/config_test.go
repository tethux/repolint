func TestConfiguredAssertionsAndSuppression(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, ".repolint.toml", `schema=1
[rules.expensive-assertion]
enabled=true
calls=['validate*']
guard='debug.Enabled'
fix='safe'
`)
	source := writeFixture(t, root, "source.go", `package p
import debug "example.test/debug"
func f() {
 //repolint:ignore expensive-assertion -- intentionally always run
 validateIgnored()
 validateState()
 if debug.Enabled {validateExisting()}
}
`)
	var diagnostics []diagnostic
	if lintErr := lintRoot(root, options{}, func(d diagnostic) { diagnostics = append(diagnostics, d) }); lintErr != nil {
		t.Fatal(lintErr)
	}
	if len(diagnostics) != 1 {
		t.Fatalf("diagnostics: %+v", diagnostics)
	}
	if fixErr := lintRoot(root, options{fix: true, fixRules: ruleExpensiveAssertion}, func(d diagnostic) { t.Errorf("remaining: %+v", d) }); fixErr != nil {
		t.Fatal(fixErr)
	}
	fixed := readFixture(t, source)
	if strings.Count(fixed, "if debug.Enabled") != 2 || strings.Contains(fixed, "if debug.Enabled {\n\t\tvalidateIgnored") {
		t.Fatalf("incorrect fix:\n%s", fixed)
	}
	if fixErr := lintRoot(root, options{fix: true}, func(d diagnostic) {}); fixErr != nil {
		t.Fatal(fixErr)
	}
	if fixed != readFixture(t, source) {
		t.Fatal("assertion fix is not idempotent")
	}
}

