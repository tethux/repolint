func TestGeneratedDomainCompilesAndPreservesCause(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "go.mod", "module example.test/runtime\n\ngo 1.26.4\n")
	writeFixture(t, root, ".repolint.toml", `schema=1
[rules.structured-error]
enabled=true
fix='structural'
generate_domains=true
constructor_roles=['operation','kind','target']
`)
	writeFixture(t, root, "source.go", `package runtime
import "fmt"
func open(cause error) error {return fmt.Errorf("open: %w",cause)}
`)
	if fixErr := lintRoot(root, options{fix: true, allowStructural: true}, func(d diagnostic) { t.Errorf("remaining: %+v", d) }); fixErr != nil {
		t.Fatal(fixErr)
	}
	writeFixture(t, root, "source_test.go", `package runtime
import (
 "errors"
 "testing"
 "example.test/runtime/errs"
)
func TestCause(t *testing.T) {
 cause:=errors.New("disk failure")
 err:=open(cause)
 if !errors.Is(err,cause) || !errors.Is(err,errs.ErrOpen) {t.Fatal("lost cause or category")}
 var operation *errs.OpError
 if !errors.As(err,&operation) || operation.Operation!="open" {t.Fatal("lost typed operation")}
}
`)
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	command := exec.CommandContext(ctx, "go", "test", "./...")
	command.Dir = root
	output, runErr := command.CombinedOutput()
	if runErr != nil {
		t.Fatalf("generated domain runtime check: %v\n%s", runErr, output)
	}
}
